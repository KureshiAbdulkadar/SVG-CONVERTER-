import { VectorLayer, ImageType } from './types';

export interface SvgOptions {
  width: number;
  height: number;
  includeMetadata?: boolean;
  figmaCompatible?: boolean;
  minify?: boolean;
  viewBox?: string;
}

// Generate human-readable, semantic, layer-grouped SVG
export function composeSvg(
  layers: VectorLayer[],
  options: SvgOptions,
  meta?: { imageType: ImageType; nodeCount: number; pathCount: number }
): string {
  const { width, height, includeMetadata = true, figmaCompatible = true, minify = false } = options;
  const viewBox = options.viewBox || `0 0 ${width} ${height}`;

  const header = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${width}" height="${height}"${
    figmaCompatible ? ' xmlns:figma="http://www.figma.com/figma/ns"' : ''
  }>`;

  let metadata = '';
  if (includeMetadata && !minify) {
    metadata = `
  <!-- Generated by VectorForge AI Vector Engine -->
  <!-- Semantic Layers: ${layers.length} | Nodes: ${meta?.nodeCount || 0} | Image Type: ${meta?.imageType || 'vector'} -->
  <metadata>
    <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#" xmlns:dc="http://purl.org/dc/elements/1.1/">
      <rdf:Description>
        <dc:creator>VectorForge</dc:creator>
        <dc:format>image/svg+xml</dc:format>
        <dc:type>${meta?.imageType || 'graphic'}</dc:type>
      </rdf:Description>
    </rdf:RDF>
  </metadata>`;
  }

  let layerGroups = '';

  for (const layer of layers) {
    if (!layer.visible) continue;

    const groupAttrs = [
      `id="${layer.id}"`,
      `data-name="${escapeXml(layer.name)}"`,
      `data-role="${layer.semanticRole}"`,
      figmaCompatible ? `figma:type="FRAME"` : '',
      `inkscape:groupmode="layer"`,
      `inkscape:label="${escapeXml(layer.name)}"`,
    ]
      .filter(Boolean)
      .join(' ');

    const visiblePaths = layer.paths.filter(p => p.visible !== false);
    if (visiblePaths.length === 0) continue;

    const pathsStr = visiblePaths
      .map(p => `    <path id="${p.id}" data-name="${escapeXml(p.name || p.id)}" fill-rule="${p.fillRule || 'evenodd'}" d="${p.d}" fill="${p.fill || layer.color}" />`)
      .join(minify ? '' : '\n');

    if (minify) {
      layerGroups += `<g ${groupAttrs}>${pathsStr}</g>`;
    } else {
      layerGroups += `\n  <g ${groupAttrs}>\n${pathsStr}\n  </g>`;
    }
  }

  const footer = minify ? '</svg>' : '\n</svg>';
  const fullSvg = `${header}${metadata}${layerGroups}${footer}`;

  return minify ? minifySvgString(fullSvg) : fullSvg;
}

// Minify SVG code: strip whitespace, comments, redundant spaces
export function minifySvgString(svg: string): string {
  return svg
    .replace(/<!--[\s\S]*?-->/g, '') // remove comments
    .replace(/>\s+</g, '><') // remove whitespace between tags
    .replace(/\s{2,}/g, ' ') // collapse multi-spaces
    .trim();
}

// Escape XML attribute characters
function escapeXml(unsafe: string): string {
  return unsafe.replace(/[<>&'"]/g, c => {
    switch (c) {
      case '<': return '&lt;';
      case '>': return '&gt;';
      case '&': return '&amp;';
      case '\'': return '&apos;';
      case '"': return '&quot;';
      default: return c;
    }
  });
}

// Generate single isolated layer SVG
export function exportSingleLayerSvg(layer: VectorLayer, width: number, height: number): string {
  return composeSvg([layer], { width, height, minify: false });
}
